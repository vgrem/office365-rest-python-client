"""Every name the tree declares is one its API publishes, and the snapshot still matches it.

A wrong permission name is invisible in a live run: the request is refused, the harness reads
the refusal as "the tenant did not grant it", and the test skips - so a typo and a missing
grant look the same. The catalogs put the published names in the repository, read from each
API's own service principal, which makes the name checkable offline.

The snapshot is generated by ``scripts/gen_permission_catalog.py``; the last class here is the
ratchet, re-reading the tenant so a snapshot that has drifted is a red test rather than a
stale answer.
"""

from __future__ import annotations

from unittest import TestCase

import office365
from office365.permissions import APPLICATION, DELEGATED, ResourceName, catalog, catalog_resources, index
from tests.decorators import requires_application
from tests.graph_case import GraphApplicationTestCase

LIBRARY = index(office365)


def _declarations():
    """(resource, kind, name) for every name the library asks for."""
    for operation in LIBRARY.declared():
        for requirement in operation.declaration.requirements():
            for kind, names in ((DELEGATED, requirement.delegated), (APPLICATION, requirement.application)):
                for name in names:
                    yield str(requirement.resource), kind, name


def _published(client, resource: str) -> dict:
    """What the tenant's service principal for ``resource`` publishes, in the snapshot's shape."""
    principal = (
        client.service_principals.find_by_name(resource, required=True)
        .select(["appRoles", "oauth2PermissionScopes"])
        .get()
        .execute_query()
    )
    roles = [row.to_json() for row in principal.app_roles or []]
    scopes = [row.to_json() for row in principal.oauth2_permission_scopes or []]
    return {
        APPLICATION: {row["value"] for row in roles},
        DELEGATED: {row["value"] for row in scopes},
        "user_consentable": {row["value"] for row in scopes if row.get("type") == "User"},
        "disabled": {row["value"] for row in [*roles, *scopes] if row.get("isEnabled") is False},
    }


class TestEveryDeclaredNameIsPublished(TestCase):
    """The gate: a declaration may only name what its API offers and can still grant."""

    def test_a_declared_name_is_one_the_api_publishes(self):
        unknown, unpublished = set(), []
        for resource, kind, name in _declarations():
            snapshot = catalog(resource)
            if snapshot is None:
                unknown.add(resource)
            elif not snapshot.publishes(name, kind):
                unpublished.append(f"{resource} does not publish {kind} {name}")
        self.assertEqual([], unpublished, "a declaration names a permission the API does not publish")
        self.assertEqual(set(), unknown, "no snapshot for this API: run scripts/gen_permission_catalog.py")


class TestANameMeansSomethingOnlyBesideItsApi(TestCase):
    def test_a_name_only_sharepoint_publishes_is_not_published_by_graph(self):
        self.assertTrue(catalog(ResourceName.SharePoint).publishes("AllSites.Manage"))
        self.assertFalse(catalog(ResourceName.Graph).publishes("AllSites.Manage"))


class TestTheSnapshotsAreInternallyConsistent(TestCase):
    def test_consent_and_state_only_name_published_permissions(self):
        for resource in catalog_resources():
            snapshot = catalog(resource)
            self.assertLessEqual(snapshot.user_consentable, snapshot.delegated, resource)
            self.assertLessEqual(snapshot.disabled, snapshot.delegated | snapshot.application, resource)


class TestTheSnapshotsStillMatchTheTenant(GraphApplicationTestCase):
    """The committed names, read back from the service principals: drift fails both ways."""

    @requires_application("Application.Read.All", "Directory.Read.All")
    def test_the_published_names_are_the_ones_committed(self):
        for resource in catalog_resources():
            published, snapshot = _published(self.client, resource), catalog(resource)
            for kind in (APPLICATION, DELEGATED):
                self.assertCountEqual(
                    published[kind],
                    snapshot.names(kind),
                    f"{resource} {kind} names have moved: run scripts/gen_permission_catalog.py",
                )
            for field in ("user_consentable", "disabled"):
                self.assertCountEqual(published[field], getattr(snapshot, field), f"{resource} {field} has moved")
