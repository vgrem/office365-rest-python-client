from __future__ import annotations

from typing import Optional

from office365.runtime.types.odata_property import odata
from office365.security.identity_accounts import IdentityAccounts


class User(IdentityAccounts):
    @odata(name="emailAddress")
    @property
    def email_address(self) -> Optional[str]:
        """Gets the emailAddress property"""
        return self.properties.get("emailAddress", None)

    @odata(name="userPrincipalName")
    @property
    def user_principal_name(self) -> Optional[str]:
        """Gets the userPrincipalName property"""
        return self.properties.get("userPrincipalName", None)

    @property
    def entity_type_name(self) -> str:
        return "microsoft.graph.security.User"
