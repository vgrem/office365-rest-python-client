#!/usr/bin/env python3
"""Write the permission catalogs from the APIs themselves.

Each API's service principal publishes what it can grant: ``appRoles`` are the application
permissions, ``oauth2PermissionScopes`` the delegated ones. This reads them and writes one
module per API under ``office365/permissions/snapshots/``, so the library can say "that name
does not exist" without a tenant - and does, in ``tests/unit/test_permission_declarations.py``.

Re-run it against a tenant and commit the diff:

    uv run python scripts/gen_permission_catalog.py

The credentials default to the ones the live tests use (``.env`` / ``OFFICE365_*``), either the
app secret or the certificate, and ``--tenant``/``--client-id``/``--client-secret`` override them.
Reading ``servicePrincipals`` needs ``Application.Read.All``; the tenant's own answer is the
only authority for what it publishes, so nothing here is typed by hand. The formatting is
already what ``ruff format`` produces, so a regeneration touches only the names that moved.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from office365.graph_client import GraphClient  # noqa: E402
from office365.permissions.catalog import Catalog  # noqa: E402
from office365.permissions.resource import ResourceName  # noqa: E402
from tests.settings import settings  # noqa: E402

_REPO_ROOT = Path(__file__).resolve().parents[1]
_OUTPUT_DIR = _REPO_ROOT / "office365" / "permissions" / "snapshots"

#: The APIs this library declares against. Adding one is the enum member, this tuple, the
#: module name below - and the snapshot itself, which is what the script writes.
RESOURCES: Tuple[ResourceName, ...] = (ResourceName.Graph, ResourceName.SharePoint)

#: The module name per API: "Microsoft Graph" is not a filename.
MODULES: Dict[str, str] = {ResourceName.Graph: "graph", ResourceName.SharePoint: "sharepoint"}

_HEADER = '''"""Which permissions {resource} publishes.

Generated by ``scripts/gen_permission_catalog.py`` from the service principal of {resource} -
do not edit by hand; re-run the script and commit what it writes.

A name is listed by the flow that asks for it, with the two facts that decide whether a grant
is possible: ``USER_CONSENTABLE`` is the part of ``DELEGATED`` a signed-in user may consent to,
and ``DISABLED`` names are still published but can no longer be granted.
"""

RESOURCE = "{resource}"

'''

_BODY = '''APPLICATION = """
{application}
"""

DELEGATED = """
{delegated}
"""

USER_CONSENTABLE = """
{user_consentable}
"""

DISABLED = """
{disabled}
"""
'''


def fetch(client: GraphClient, resource: ResourceName) -> Catalog:
    """Read ``resource``'s own service principal and keep the facts that decide a grant."""
    principal = (
        client.service_principals.find_by_name(resource, required=True)
        .select(["appRoles", "oauth2PermissionScopes"])
        .get()
        .execute_query()
    )
    roles = [row.to_json() for row in principal.app_roles or []]
    scopes = [row.to_json() for row in principal.oauth2_permission_scopes or []]
    return Catalog(
        resource=resource,
        application=frozenset(_values(roles)),
        delegated=frozenset(_values(scopes)),
        user_consentable=frozenset(row["value"] for row in scopes if row.get("type") == "User"),
        disabled=frozenset(row["value"] for row in [*roles, *scopes] if row.get("isEnabled") is False),
    )


def _values(rows: Iterable[dict]) -> List[str]:
    """The published names of ``rows``; a permission appears once per member type."""
    return [row["value"] for row in rows if row.get("value")]


def render(catalog: Catalog) -> str:
    """The snapshot module for ``catalog``, already formatted."""
    return _HEADER.format(resource=catalog.resource) + _BODY.format(
        application=_block(catalog.application),
        delegated=_block(catalog.delegated),
        user_consentable=_block(catalog.user_consentable),
        disabled=_block(catalog.disabled),
    )


def _block(names: Iterable[str]) -> str:
    """One name per line, sorted - so a diff shows the names that changed, not the wrapping."""
    return "\n".join(sorted(names))


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = _parse_args(argv)
    client = _client(args)
    for resource in RESOURCES:
        catalog = fetch(client, resource)
        path = _OUTPUT_DIR / f"{MODULES[str(resource)]}.py"
        path.write_text(render(catalog), encoding="utf-8")
        counts = f"{len(catalog.application)} application, {len(catalog.delegated)} delegated"
        print(f"{path.relative_to(_REPO_ROOT)}: {counts}")
    return 0


def _client(args: argparse.Namespace) -> GraphClient:
    client = GraphClient(tenant=args.tenant)
    if args.client_secret:
        return client.with_client_secret(args.client_id, args.client_secret)
    if args.cert_thumbprint and args.cert_key:
        key = Path(args.cert_key).read_text(encoding="utf-8")
        return client.with_certificate(args.client_id, args.cert_thumbprint, key)
    raise SystemExit("no credential: pass --client-secret, or configure the certificate the tests use")


def _parse_args(argv: Optional[Sequence[str]]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tenant", default=settings.tenant)
    parser.add_argument("--client-id", default=settings.client_id)
    parser.add_argument("--client-secret", default=settings.client_secret)
    parser.add_argument("--cert-thumbprint", default=settings.cert_thumbprint)
    parser.add_argument("--cert-key", default=settings.cert_path)
    return parser.parse_args(argv)


if __name__ == "__main__":
    raise SystemExit(main())
